#!/usr/bin/env node
/**
 * Generate the Markdown twin of every HTML page into `md/`.
 *
 * The middleware serves these when a client negotiates `text/markdown`, so
 * they must never drift from the HTML. `node --test` fails if they do; run
 * this script after editing any page:
 *
 *     node scripts/build-markdown.mjs
 *
 * Pass --check to verify without writing (what CI and the test suite do).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { htmlToMarkdown } from '../lib/markdown.mjs';

export const ORIGIN = 'https://www.pgupai.com';
export const OUTPUT_DIR = 'md';

/** Pages that are not content: social-share shims and the like. */
const EXCLUDED = new Set(['x.html']);

/** The error page: it gets a twin, but it is not a route agents navigate to. */
export const NOT_FOUND_PAGE = '404.html';

/** Generated route table consumed by the Edge Middleware. */
export const ROUTES_MODULE = 'lib/routes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Map a repo-relative HTML path to the clean URL vercel.json serves it at. */
export function urlPathFor(file) {
  const withoutExtension = file.replace(/\.html$/, '');
  if (withoutExtension === 'index') return '/';
  if (withoutExtension.endsWith('/index')) return `/${withoutExtension.slice(0, -'/index'.length)}`;
  return `/${withoutExtension}`;
}

/** Map a repo-relative HTML path to its Markdown twin under `md/`. */
export function markdownPathFor(file) {
  return path.posix.join(OUTPUT_DIR, file.replace(/\.html$/, '.md'));
}

/** Every content page in the repo, in stable order. */
export function contentPages(root = ROOT) {
  const pages = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(path.join(root, dir || '.'), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const rel = dir ? path.posix.join(dir, entry.name) : entry.name;
      if (entry.isDirectory()) {
        if (['guides', 'compare'].includes(rel)) walk(rel);
        continue;
      }
      if (!entry.name.endsWith('.html')) continue;
      if (EXCLUDED.has(rel)) continue;
      pages.push(rel);
    }
  };
  walk('');
  return pages;
}

/** Render one page's Markdown twin, including its canonical footer. */
export function renderPage(file, root = ROOT) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const urlPath = urlPathFor(file);
  const canonical = `${ORIGIN}${urlPath === '/' ? '/' : urlPath}`;
  const body = htmlToMarkdown(html, { origin: ORIGIN, canonical });
  const footer = [
    '---',
    '',
    `_Markdown representation of [${canonical}](${canonical}). ` +
      `Site map: [${ORIGIN}/sitemap.xml](${ORIGIN}/sitemap.xml) · ` +
      `Fact sheet for agents: [${ORIGIN}/llms.txt](${ORIGIN}/llms.txt)._`,
    '',
  ].join('\n');
  return `${body}\n${footer}`;
}

/** Render the generated route table the middleware imports. */
export function renderRoutes(root = ROOT) {
  const entries = contentPages(root)
    .filter((file) => file !== NOT_FOUND_PAGE)
    .map((file) => [urlPathFor(file), `/${markdownPathFor(file)}`])
    .sort((a, b) => a[0].localeCompare(b[0]));

  const lines = entries.map(([url, md]) => `  '${url}': '${md}',`).join('\n');
  return [
    '// GENERATED by scripts/build-markdown.mjs — do not edit by hand.',
    '// Maps every clean URL to the Markdown twin the middleware serves for it.',
    '',
    'export const ROUTES = Object.freeze({',
    lines,
    '});',
    '',
    '/** Body served when an agent negotiates Markdown for a path that does not exist. */',
    `export const NOT_FOUND_MARKDOWN = '/${markdownPathFor(NOT_FOUND_PAGE)}';`,
    '',
  ].join('\n');
}

/**
 * Build every twin.
 *
 * @param {{check?: boolean, root?: string}} [options]
 * @returns {{path: string, stale: boolean}[]}
 */
export function build({ check = false, root = ROOT } = {}) {
  const results = [];
  for (const file of contentPages(root)) {
    const target = markdownPathFor(file);
    const absolute = path.join(root, target);
    const next = renderPage(file, root);
    const current = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : null;
    const stale = current !== next;
    if (stale && !check) {
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, next);
    }
    results.push({ path: target, stale });
  }

  const routesPath = path.join(root, ROUTES_MODULE);
  const nextRoutes = renderRoutes(root);
  const currentRoutes = fs.existsSync(routesPath) ? fs.readFileSync(routesPath, 'utf8') : null;
  const routesStale = currentRoutes !== nextRoutes;
  if (routesStale && !check) fs.writeFileSync(routesPath, nextRoutes);
  results.push({ path: ROUTES_MODULE, stale: routesStale });

  return results;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const results = build({ check });
  const stale = results.filter((r) => r.stale);
  for (const result of results) {
    console.log(`${result.stale ? (check ? 'STALE  ' : 'write  ') : 'ok     '}${result.path}`);
  }
  if (check && stale.length) {
    console.error(`\n${stale.length} Markdown twin(s) out of date. Run: node scripts/build-markdown.mjs`);
    process.exit(1);
  }
  console.log(`\n${results.length} page(s), ${check ? `${stale.length} stale` : `${stale.length} written`}`);
}
